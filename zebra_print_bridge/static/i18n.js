/**
 * The viewer's language: the one saved by the user, else the first browser language we have
 * (exact match, then its base: fr-CA -> fr; any Portuguese -> pt-BR), else English.
 */
export function detectLanguage(saved, browserLanguages) {
  if (saved && Object.hasOwn(I18N, saved)) return saved;
  for (const tag of browserLanguages || []) {
    const language = String(tag).toLowerCase();
    const match = Object.keys(LANGUAGES).find((code) => code.toLowerCase() === language);
    if (match) return match;
    const base = language.split('-')[0];
    if (Object.hasOwn(I18N, base)) return base;
    if (base === 'pt') return 'pt-BR';
  }
  return 'en';
}

function savedLanguage() {
  try { return localStorage.getItem('lang'); } catch { return null; }
}

function browserLanguages() {
  if (typeof navigator === 'undefined') return [];
  return navigator.languages?.length ? navigator.languages : [navigator.language];
}

export let currentLang = detectLanguage(savedLanguage(), browserLanguages());

export function setLanguage(code) {
  currentLang = Object.hasOwn(I18N, code) ? code : 'en';
  try { localStorage.setItem('lang', currentLang); } catch {}
}

function lookup(key) {
  return I18N[currentLang]?.[key] ?? I18N.en[key] ?? key;
}

/** Plain text: html`` escapes it like any other value. */
export function t(key, params = {}) {
  return lookup(key).replace(/\{(\w+)\}/g, (_, name) => params[name] ?? '');
}

/** For translations that contain markup (<b>...</b>): params are escaped unless they are Html. */
export function tHtml(key, params = {}) {
  return raw(lookup(key).replace(/\{(\w+)\}/g, (_, name) => render(params[name])));
}

export function applyStaticTranslations() {
  document.documentElement.lang = currentLang;
  document.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
}
